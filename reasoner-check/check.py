"""OWL consistency check for MD-Models OWL output.

For each input model the script generates the OWL serialisation with MD-Models,
parses it with rdflib, loads it into owlready2, and runs the HermiT reasoner to
test logical consistency. An OWL-RL closure with owlrl is computed as a second,
independent check. Results are written to ``report.json``.

Run with:  uv run check.py
"""

from __future__ import annotations

import importlib.metadata
import json
import os
import pathlib
import sys
import tempfile

import mdmodels_core as mdm
import owlrl
import rdflib
from owlready2 import World, sync_reasoner_hermit
from owlready2.base import OwlReadyInconsistentOntologyError

HERE = pathlib.Path(__file__).parent
DEMO_MODEL = HERE.parent / "model.md"
ENZYMEML_MODEL = HERE / "models" / "enzymeml_v2.md"

RDFS = rdflib.RDFS
OWL = rdflib.OWL


def _pkg_version(name: str) -> str:
    try:
        return importlib.metadata.version(name)
    except importlib.metadata.PackageNotFoundError:  # pragma: no cover
        return "unknown"


def generate_owl(md_path: pathlib.Path) -> str:
    return mdm.DataModel.from_markdown(str(md_path)).convert_to(mdm.Templates.Owl)


def summarise_graph(graph: rdflib.Graph) -> dict:
    classes = {s for s in graph.subjects(rdflib.RDF.type, OWL.Class) if isinstance(s, rdflib.URIRef)}
    obj_props = {s for s in graph.subjects(rdflib.RDF.type, OWL.ObjectProperty)}
    data_props = {s for s in graph.subjects(rdflib.RDF.type, OWL.DatatypeProperty)}
    external = set()
    for _s, p, o in graph:
        if p in (RDFS.subClassOf, RDFS.subPropertyOf) and isinstance(o, rdflib.URIRef):
            if "mdmodel.net" not in str(o) and str(RDFS) not in str(o):
                external.add(str(o))
    return {
        "triples": len(graph),
        "classes": len(classes),
        "object_properties": len(obj_props),
        "datatype_properties": len(data_props),
        "external_terms": sorted(external),
        "external_term_count": len(external),
    }


def hermit_consistency(turtle: str) -> dict:
    graph = rdflib.Graph().parse(data=turtle, format="turtle")
    with tempfile.NamedTemporaryFile("wb", suffix=".rdf", delete=False) as fh:
        graph.serialize(destination=fh.name, format="xml")
        rdf_path = fh.name

    world = World()
    onto = world.get_ontology("file://" + rdf_path).load()
    result = {"reasoner": "HermiT", "loaded_classes": len(list(onto.classes()))}
    try:
        with onto:
            sync_reasoner_hermit(world, infer_property_values=True)
        result["consistent"] = True
        result["inconsistent_classes"] = []
    except OwlReadyInconsistentOntologyError as exc:  # pragma: no cover - defensive
        result["consistent"] = False
        result["error"] = str(exc)
    finally:
        os.unlink(rdf_path)
    return result


def owlrl_closure(turtle: str) -> dict:
    graph = rdflib.Graph().parse(data=turtle, format="turtle")
    before = len(graph)
    owlrl.DeductiveClosure(owlrl.OWLRL_Semantics).expand(graph)
    after = len(graph)
    nothing_members = list(graph.subjects(rdflib.RDF.type, OWL.Nothing))
    return {
        "reasoner": "owlrl (OWL-RL)",
        "triples_before": before,
        "triples_after_closure": after,
        "inferred_triples": after - before,
        "owl_nothing_members": [str(x) for x in nothing_members],
        "consistent": not nothing_members,
    }


def run_one(name: str, md_path: pathlib.Path) -> dict:
    turtle = generate_owl(md_path)
    graph = rdflib.Graph()
    parse_error = None
    try:
        graph.parse(data=turtle, format="turtle")
    except Exception as exc:  # pragma: no cover - defensive
        parse_error = repr(exc)

    entry: dict = {
        "model": name,
        "source": str(md_path.relative_to(HERE.parent)),
        "owl_bytes": len(turtle.encode("utf-8")),
        "rdflib_parses": parse_error is None,
    }
    if parse_error:
        entry["parse_error"] = parse_error
        return entry

    entry["graph"] = summarise_graph(graph)
    entry["hermit"] = hermit_consistency(turtle)
    entry["owlrl"] = owlrl_closure(turtle)
    entry["consistent"] = bool(entry["hermit"].get("consistent")) and bool(
        entry["owlrl"].get("consistent")
    )
    return entry


def main() -> int:
    report = {
        "description": (
            "Consistency check of the OWL serialisations generated by MD-Models. "
            "Each ontology is parsed with rdflib, classified with HermiT through "
            "owlready2, and closed under OWL-RL with owlrl."
        ),
        "mdmodels_core": _pkg_version("mdmodels-core"),
        "reasoners": {
            "hermit": "owlready2 " + _pkg_version("owlready2"),
            "owlrl": _pkg_version("owlrl"),
        },
        "results": [],
    }
    for name, path in [
        ("experiment-demo", DEMO_MODEL),
        ("enzymeml-v2", ENZYMEML_MODEL),
    ]:
        print(f"checking {name} ...", flush=True)
        report["results"].append(run_one(name, path))

    out = HERE / "report.json"
    out.write_text(json.dumps(report, indent=2) + "\n")
    print(f"\nwrote {out}")
    for res in report["results"]:
        state = "consistent" if res.get("consistent") else "NOT consistent"
        ext = res.get("graph", {}).get("external_term_count", 0)
        print(f"  {res['model']:>16}: {state}  ({ext} external ontology terms)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
